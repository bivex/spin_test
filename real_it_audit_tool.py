def main():
    print("=================================================================", flush=True)
    print("   REAL-WORLD IT SYSTEM SECURITY & FORMAL AUDIT ENGINE          ", flush=True)
    print("=================================================================", flush=True)
    
    print("\n[1/4] Collecting live system diagnostics...", flush=True)
    sys_diag = get_system_diagnostics()
    print(f" -> Host: {sys_diag['platform']}", flush=True)
    print(f" -> Cores: {sys_diag['cpu_count']}, Load: {sys_diag['load_1min']}, Processes: {sys_diag['process_count']}", flush=True)
    
    print("\n[2/4] Generating formal Promela concurrency model (generated_audit.pml)...", flush=True)
    promela_code = generate_promela_spec(sys_diag['cpu_count'], sys_diag['process_count'])
    promela_file = "generated_audit.pml"
    with open(promela_file, "w") as f:
        f.write(promela_code)
    print(" -> Model generated successfully.", flush=True)
    
    print("\n[3/4] Running SPIN formal C-verifier pipeline (spin -a -> pan.c -> gcc -> ./pan)...", flush=True)
    verif_res = run_spin_verification(promela_file)
    if verif_res['success']:
        print(" -> SPIN Verification SUCCESSFUL (0 errors found).", flush=True)
    else:
        print(f" -> Verification Error: {verif_res.get('error')}", flush=True)
        
    print("\n[4/4] Exporting B2B Audit Report (audit_report_REAL.md)...", flush=True)
    report_md = create_audit_report(sys_diag, verif_res)
    report_file = "audit_report_REAL.md"
    with open(report_file, "w") as f:
        f.write(report_md)
    print(f" -> Report written to {report_file}", flush=True)
    
    print("\n=================================================================", flush=True)
    print("  AUDIT COMPLETED: Real system metrics & formal proof generated! ", flush=True)
    print("=================================================================", flush=True)

if __name__ == "__main__":
    main()
